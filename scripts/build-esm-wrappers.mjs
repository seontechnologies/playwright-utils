#!/usr/bin/env node
/**
 * Generates the ESM entry points listed under `import` in package.json `exports`.
 *
 * Each entry is a thin ES module that loads the CommonJS build through `createRequire` and
 * re-exports its named exports. ESM and CJS consumers therefore share one module instance, and
 * the CommonJS graph is always loaded by Node's CommonJS loader. Loading it through the ESM
 * loader instead breaks on Node 22 when loader hooks are registered (Playwright registers them
 * in `"type": "module"` projects): `require()` of a dependency that ships `module-sync` ESM fails
 * with "request for './index.js' is not in cache".
 *
 * Run after the CJS build:  node scripts/build-esm-wrappers.mjs
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(import.meta.url)
const pkg = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf-8'))

const LOCAL_NAMES = new Set(['__require', '__module'])
const IDENTIFIER = /^[A-Za-z_$][\w$]*$/
// Words that cannot be binding names in an ES module (strict mode)
const RESERVED = new Set(
  (
    'await break case catch class const continue debugger default delete do else enum export ' +
    'extends false finally for function if implements import in instanceof interface let new ' +
    'null package private protected public return static super switch this throw true try ' +
    'typeof var void while with yield arguments eval'
  ).split(' ')
)

let count = 0
for (const [subpath, targets] of Object.entries(pkg.exports)) {
  if (typeof targets !== 'object' || !targets.import || !targets.require) {
    continue
  }

  const cjsFile = resolve(root, targets.require)
  const esmFile = resolve(root, targets.import)
  if (!esmFile.endsWith('.mjs')) {
    throw new Error(
      `exports["${subpath}"].import must point at a .mjs file, got ${targets.import}`
    )
  }

  const names = Object.keys(require(cjsFile)).filter(
    (name) => name !== 'default'
  )
  for (const name of names) {
    if (!IDENTIFIER.test(name) || RESERVED.has(name) || LOCAL_NAMES.has(name)) {
      throw new Error(
        `exports["${subpath}"]: cannot re-export "${name}" from an ES module wrapper`
      )
    }
  }

  let specifier = relative(dirname(esmFile), cjsFile).split('\\').join('/')
  if (!specifier.startsWith('.')) specifier = `./${specifier}`

  const lines = [
    '// Generated by scripts/build-esm-wrappers.mjs. Do not edit.',
    "import { createRequire } from 'node:module'",
    '',
    'const __require = createRequire(import.meta.url)',
    `const __module = __require('${specifier}')`,
    '',
    ...(names.length > 0
      ? [`export const { ${names.join(', ')} } = __module`]
      : []),
    'export default __module',
    ''
  ]

  mkdirSync(dirname(esmFile), { recursive: true })
  writeFileSync(esmFile, lines.join('\n'))
  count++
}

console.log(`✅  Generated ${count} ESM entry points`)
